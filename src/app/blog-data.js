export const getBlogsByLanguage = (language) => {
  return blogData[language] || blogData.en;
};

export const getFeaturedBlogs = (language, limit = 3) => {
  const blogs = getBlogsByLanguage(language);
  return blogs.filter((blog) => blog.featured).slice(0, limit);
};

export const getBlogBySlug = (slug, language) => {
  const blogs = getBlogsByLanguage(language);
  return blogs.find((blog) => blog.slug === slug);
};

export const getAllBlogs = (language, limit = null) => {
  const blogs = getBlogsByLanguage(language);
  return limit ? blogs.slice(0, limit) : blogs;
};

export const getBlogsByCategory = (category, language) => {
  const blogs = getBlogsByLanguage(language);
  return blogs.filter((blog) => blog.category === category);
};

export const getBlogsByTag = (tag, language) => {
  const blogs = getBlogsByLanguage(language);
  return blogs.filter((blog) => blog.tags.includes(tag));
};
